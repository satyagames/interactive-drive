/**
 * Writes `exhibits` in content/arena.seed.json: the data the content-driven
 * 3D objects read (docs/content-backup/10-3d-integration-plan.md §2, phase
 * LD-C). Everything comes from the 2D-site backup in docs/content-backup/data
 * and from the seed's own stations, so the world shows exactly what the
 * panels show:
 *
 *   winsBoard       metrics.json wins_fy26 / wins_fy25
 *   thankItForward  metrics.json thank_it_forward
 *   brightStar      metrics.json brightstar
 *   learningGarden  metrics.json learning
 *   memoryLane      events.json (every album; its highlight image if one was imported)
 *   newsstand       the PDF links of station innovation_2 (newest first)
 *   signposts       links.json Find it fast / Function / Others
 *   champions       deloitte-chronicles.json (the names the 2D site printed)
 *   mascots         Percy's greeting (copy-deck) and the five district buddies
 *
 * Run after tools/site-export/import_site_export.py, then content:check:
 *
 *   node tools/site-export/build-exhibits.mjs
 *
 * Positions and sizes are not content: they live in src/config.js
 * (`rebuild.showcase`). No network; no people data beyond names already shown.
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..')
const data = (name) => JSON.parse(readFileSync(join(root, 'docs', 'content-backup', 'data', name), 'utf8'))
const seedPath = join(root, 'content', 'arena.seed.json')
const seed = JSON.parse(readFileSync(seedPath, 'utf8'))

const metrics = data('metrics.json')
const events = data('events.json')
const links = data('links.json')
const chronicles = data('deloitte-chronicles.json')

const stations = new Map(
  [seed.hq, seed.rfpGate, ...seed.territories, ...seed.pillars].flatMap((d) => d.stations).map((s) => [s.id, s]),
)
const need = (id) => {
  if (!stations.has(id)) throw new Error(`station ${id} is missing from the seed`)
  return id
}
/** "Pursuit Wins, FY26 (site snapshot, Sep 2025)" -> { title: "Pursuit Wins, FY26", caption: "site snapshot, Sep 2025" } */
const splitTitle = (text) => {
  const match = /^(.*?)\s*\((.*)\)\s*$/.exec(text)
  return match ? { title: match[1], caption: match[2] } : { title: text, caption: '' }
}
/** "Thank It Forward stats, June 2023 - December 2024" -> "June 2023 – December 2024" */
const period = (text) => (/,\s*(.*)$/.exec(text)?.[1] ?? '').replace(' - ', ' – ')
const slug = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '').slice(0, 60)
const count = (value) => Number.parseInt(String(value).replace(/[^0-9]/g, ''), 10)

const winsSet = (key) => {
  const { title, caption } = splitTitle(metrics[key].title)
  return { title: title.replace(/^Pursuit Wins,\s*/, ''), caption, rows: metrics[key].rows.map(({ label, value }) => ({ label, value })) }
}

const percyGreeting = stations.get(need('gate_how_to_drive')).body.split('\n\n')[0].replace(/\n/g, ' ')

const albums = events.map((e) => {
  const image = `content/site/culture-4-${slug(e.title)}.webp`
  return {
    title: e.title,
    when: e.when ?? null,
    place: e.place ?? null,
    photos: e.photos,
    image: existsSync(join(root, 'public', image)) ? image : null,
  }
})

const issues = stations
  .get(need('innovation_2'))
  .links.filter((l) => l.url.endsWith('.pdf'))
  .map((l) => ({ label: l.label.replace(/^The Intelligence Update,\s*/, '').replace(/\s*\(PDF\)$/, ''), url: l.url }))

const exhibits = {
  note: 'Generated by tools/site-export/build-exhibits.mjs from docs/content-backup/data and the stations above. Positions live in src/config.js (rebuild.showcase).',
  mascots: {
    percy: { district: 'rfp_gate', name: 'Percy', greeting: percyGreeting, station: 'gate_how_to_drive' },
    // The five pillar buddies (doc 10 §2.1): each gives the next-stamp hint.
    buddies: ['rnr', 'lnd', 'toolkit', 'innovation', 'culture'].map((id) => ({ id, district: id })),
  },
  winsBoard: {
    district: 'hq',
    station: need('hq_org'),
    heading: 'Pursuit Wins',
    sets: [winsSet('wins_fy26'), winsSet('wins_fy25')],
  },
  thankItForward: {
    district: 'rnr',
    station: need('rnr_1'),
    title: 'Thank It Forward',
    period: period(metrics.thank_it_forward.title),
    awards: metrics.thank_it_forward.rows.map(({ label, value }) => ({ id: slug(label.replace(/ Awards?$/, '')), label, count: count(value) })),
  },
  brightStar: {
    district: 'rnr',
    station: need('rnr_3'),
    title: 'BrightStar Awards',
    period: period(metrics.brightstar.title),
    categories: metrics.brightstar.rows.map(({ label, value }) => ({ label, count: count(value) })),
  },
  memoryLane: { district: 'culture', station: need('culture_4'), title: "Insiders' Scoop · Memory Lane", albums },
  newsstand: { district: 'innovation', station: need('innovation_2'), title: 'The Intelligence Update', issues },
  learningGarden: {
    district: 'lnd',
    station: need('lnd_3'),
    bars: metrics.learning.rows.map(({ label, value }) => ({ label, value: count(value), unit: 'hours' })),
  },
  signposts: {
    district: 'toolkit',
    station: need('toolkit_3'),
    groups: ['Find it fast', 'Function', 'Others'].map((title) => ({ title, links: links[title].map(({ label, url }) => ({ label, url })) })),
  },
  champions: {
    station: need('culture_3'),
    title: 'Deloitte Chronicles',
    names: chronicles.map((c) => c.name.trim()),
  },
}

// Keep the key order stable: exhibits sits just before gamification.
const out = {}
for (const [key, value] of Object.entries(seed)) {
  if (key === 'exhibits') continue
  if (key === 'gamification') out.exhibits = exhibits
  out[key] = value
}
writeFileSync(seedPath, `${JSON.stringify(out, null, 2)}\n`)
console.log(
  `[exhibits] ${albums.length} albums (${albums.filter((a) => a.image).length} with a photo), ${issues.length} issues, ` +
    `${exhibits.signposts.groups.reduce((n, g) => n + g.links.length, 0)} signposts, ${exhibits.champions.names.length} champions, ` +
    `${exhibits.thankItForward.awards.reduce((n, a) => n + a.count, 0)} trophies -> content/arena.seed.json`,
)
